import fs from 'node:fs';
import path from 'node:path';
import { buildDDL, buildRLS, buildStorageSQL } from '../src/lib/schema';

/** Regenerates supabase/migrations/20261009000000_init.sql from the resource registry. */
const out = path.join(process.cwd(), 'supabase', 'migrations', '20261009000000_init.sql');
const sql = `-- Generated by \`npm run gen-migration\` from src/lib/resources.ts. Safe to re-run (idempotent).
-- Run in Supabase: SQL Editor → New query → paste → Run.

-- ============ TABLES ============
${buildDDL()}

-- ============ ROW LEVEL SECURITY ============
${buildRLS()}

-- ============ STORAGE (uploads bucket) ============
${buildStorageSQL()}
`;
fs.mkdirSync(path.dirname(out), { recursive: true });
fs.writeFileSync(out, sql);
console.log(`Wrote ${out} (${sql.length} bytes)`);
